// Задача 1.1
// Вывести квадрат NxN: выше побочной диагонали — 0, на диагонали — 1, ниже — 2.
#include <iostream>
using namespace std;

int main() {
    int n;              // размер квадрата (число строк и столбцов)
    cin >> n;           // читаем N

    for (int i = 0; i < n; i++) {          // i — номер строки (0..n-1)
        for (int j = 0; j < n; j++) {      // j — номер столбца (0..n-1)
            if (j != 0) cout << ' ';       // пробел-разделитель перед всеми числами, кроме первого в строке

            int s = i + j;                 // сумма индексов определяет положение относительно побочной диагонали
            if (s < n - 1) {
                cout << '0';               // выше побочной диагонали (правее): i+j < n-1
            }
            else if (s == n - 1) {
                cout << '1';               // на побочной диагонали: i+j == n-1
            }
            else {
                cout << '2';               // ниже побочной диагонали (левее): i+j > n-1
            }
        }
        cout << '\n';                      // конец строки
    }
    return 0;
}

// Задача 1.2
// Тот же квадрат, но через три цикла for: сначала нули, потом 1, потом двойки.
#include <iostream>
using namespace std;

int main() {
    int n;              // размер квадрата
    cin >> n;           // читаем N

    for (int i = 0; i < n; i++) {              // i — номер строки (0..n-1)
        // Блок 1: (n-1-i) нулей, каждый с пробелом ПОСЛЕ (после нулей всегда идёт единица)
        for (int k = 0; k < n - 1 - i; k++)
            cout << "0 ";

        // Блок 2: ровно одна единица (без пробелов вокруг — она зажата между блоками)
        cout << "1";

        // Блок 3: i двоек, каждая с пробелом ПЕРЕД (перед первой двойкой стоит единица)
        for (int k = 0; k < i; k++)
            cout << " 2";

        cout << '\n';                          // конец строки
    }
    return 0;
}

// Задача 2
// Поле NxM, грибы '*', в остальных клетках — число грибов в 8 соседних клетках.
// Все символы выводятся БЕЗ пробелов.
#include <iostream>
#include <vector>
#include <set>
using namespace std;

int main() {
    int n, m;                       // n — число строк, m — число столбцов
    cin >> n >> m;

    int w;                          // w — количество грибов
    cin >> w;

    // Матрица поля n x m, изначально заполнена символами '0'
    vector<vector<char>> field(n, vector<char>(m, '0'));

    // Множество координат грибов (в 0-индексации) — для быстрой проверки «есть ли гриб»
    set<pair<int,int>> mushrooms;

    // Читаем w координат грибов
    for (int k = 0; k < w; k++) {
        int r, c;                   // r — строка, c — столбец (в условии 1-индексация)
        cin >> r >> c;
        r--; c--;                   // переводим в 0-индексацию
        mushrooms.insert({r, c});   // запоминаем координату гриба
        field[r][c] = '*';          // отмечаем гриб на поле
    }

    // Обходим каждую клетку поля
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            if (field[i][j] == '*') continue;   // клетку-гриб не трогаем

            int cnt = 0;                        // счётчик грибов-соседей

            // Перебираем 8 направлений: di, dj ∈ {-1, 0, 1}, кроме (0,0)
            for (int di = -1; di <= 1; di++) {
                for (int dj = -1; dj <= 1; dj++) {
                    if (di == 0 && dj == 0) continue;   // саму клетку пропускаем

                    int ni = i + di, nj = j + dj;       // координаты соседа

                    // Проверяем: не вышли за границы поля И в клетке есть гриб
                    if (ni >= 0 && ni < n && nj >= 0 && nj < m
                        && mushrooms.count({ni, nj}))
                        cnt++;                          // нашли ещё один гриб-сосед
                }
            }

            // Записываем количество соседей как символ-цифру: '0' + cnt
            field[i][j] = char('0' + cnt);
        }
    }

    // Вывод: каждая строка — без пробелов, между строками — перевод строки
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) cout << field[i][j];
        cout << '\n';
    }
    return 0;
}

// Задача 3
// Последовательность «look-and-say»: каждая строка описывает предыдущую.
// Пример: 1 → 11 → 21 → 1211 → 111221 → ...
// На вход: x (первый член) и n (номер нужного члена). Вывести n-й член.
#include <iostream>
#include <string>
using namespace std;

int main() {
    string x;               // первый член последовательности (читаем как строку — может быть "0")
    int n;                  // номер нужного члена (1-based)
    cin >> x >> n;

    string s = x;           // текущий член последовательности

    // Выполняем (n-1) преобразований, чтобы из 1-го члена получить n-й
    for (int step = 1; step < n; step++) {
        string result;      // сюда собираем следующий член
        int i = 0;          // позиция начала текущей группы одинаковых цифр

        while (i < (int)s.size()) {
            int j = i;
            // Ищем конец группы: пока символы совпадают с s[i]
            while (j < (int)s.size() && s[j] == s[i]) j++;

            // Группа — это s[i..j-1], её длина = j - i
            result += to_string(j - i);   // сначала количество
            result += s[i];               // потом сама цифра

            i = j;                        // переходим к следующей группе
        }

        s = result;         // текущим членом становится только что построенный
    }

    cout << s << '\n';      // выводим n-й член
    return 0;
}